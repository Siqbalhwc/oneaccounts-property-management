/**
 * Small, dependency-free icon set. Kept as plain inline SVG (same stroke
 * style the login page's password show/hide toggle already used) rather
 * than pulling in an icon library just for a handful of glyphs.
 *
 * Deliberately generic for "brand" contacts (phone/video instead of the
 * actual WhatsApp/YouTube logos) -- those marks are trademarked, and a
 * plain icon + label communicates the same thing without reproducing them.
 */

